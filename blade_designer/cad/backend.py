"""Kernel-independent interface. Shapes must remain inside the CAD process."""
from typing import Protocol,Any

class CadBackend(Protocol):
    def create_surface(self,rows,count,parameters=None,spans=None,tangents=None)->Any: ...
    def create_blade_solid(self,sections,tolerance_mm:float)->Any: ...
    def create_hub_solid(self,flow_zr,backside_zr,bore_radius_mm:float)->Any: ...
    def boolean_union(self,blade,hub)->Any: ...
    def apply_fillet(self,shape,root_edges,radius_mm:float)->Any: ...
    def validate_solid(self,shape)->dict: ...
    def export_step(self,shape,path)->None: ...
    def read_step(self,path)->Any: ...
